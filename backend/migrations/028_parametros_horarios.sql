-- Ejecutar en el esquema del gimnasio, con commit_gym_transaction ya instalada.
-- Se puede reejecutar tras un fallo o conservar los datos si se revierte el código.
begin;

do $$
declare
  secuencia text;
begin
  if to_regclass('public."CONFIGURACION_GIMNASIO"') is null then
    create table public."CONFIGURACION_GIMNASIO" (
      id_config bigint generated by default as identity primary key,
      capacidad_total bigint not null default 30,
      capacidad_por_hora bigint not null default 10
    );

    alter table public."CONFIGURACION_GIMNASIO" enable row level security;
    revoke all on table public."CONFIGURACION_GIMNASIO" from public, anon, authenticated;
    grant select, insert, update on table public."CONFIGURACION_GIMNASIO" to service_role;
    create policy configuracion_gimnasio_backend on public."CONFIGURACION_GIMNASIO"
      for all to service_role using (true) with check (true);

    secuencia := pg_get_serial_sequence('public."CONFIGURACION_GIMNASIO"', 'id_config');
    execute format('revoke all on sequence %s from public, anon, authenticated', secuencia);
    execute format('grant usage, select, update on sequence %s to service_role', secuencia);
  end if;
end;
$$;

alter table public."CONFIGURACION_GIMNASIO"
  add column if not exists parametros_horarios jsonb not null
    default '{"hora_inicio":"06:00","duracion_minutos":60,"cupos":10}'::jsonb
    check (jsonb_typeof(parametros_horarios) = 'object');

notify pgrst, 'reload schema';
commit;
