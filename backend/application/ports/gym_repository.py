"""Contrato de persistencia utilizado por los casos de uso del gimnasio."""
from typing import Any, Protocol, TypeVar
from application.operations.contracts import GymQuery, GymCommand
from domain.ports import PasswordHasher
from domain.models.resources import Resource
from application.read_models import AttendanceCriteria, AttendancePage, PageRequest

T = TypeVar("T")


class GymRepository(Protocol):
    def attendance_page(self, criteria: AttendanceCriteria, request: PageRequest) -> AttendancePage: ...
    def query(self, query: GymQuery[T], passwords: PasswordHasher | None = None) -> T: ...
    def execute(self, command: GymCommand[T], passwords: PasswordHasher | None = None) -> T: ...
    def refresh(self, resources: tuple[Resource, ...] | None = None) -> None: ...
    def validate_admin_registration_schema(self) -> None: ...
    def enroll(self, payload: dict[str, Any]) -> dict[str, Any] | None: ...
    def save_settings(self, payload: dict[str, Any]) -> dict[str, Any] | None: ...
    def save_attendance(self, row, expected_version, audit) -> dict | None: ...
