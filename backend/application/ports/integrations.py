"""Contratos de autenticación, pagos y notificaciones."""
from typing import Any, Protocol


class IdentityProvider(Protocol):
    def verify(self, credential: str) -> dict: ...


class SessionProvider(Protocol):
    def validate_configuration(self) -> None: ...
    def issue(self, profile: dict) -> str: ...
    def normalize(self, profile: dict, token: str = "") -> dict: ...


class PaymentGateway(Protocol):
    configured: bool
    def validate_configuration(self) -> None: ...
    def get_checkout_session(self, session_id: str) -> Any: ...
    def expire_checkout_session(self, session_id: str) -> Any: ...
    def create_store_checkout(self, order: dict, **kwargs) -> dict: ...
    def create_preregistration_checkout(self, preregistration: dict) -> dict: ...
    def find_preregistration_checkout(self, preregistration: dict) -> Any | None: ...


class EmailSender(Protocol):
    def send(self, payload: dict, event_key: str) -> str: ...


class NotificationQueue(Protocol):
    def claim(self, event_key: str | None = None) -> dict | None: ...
    def finish(self, job: dict, **outcome) -> None: ...


class MembershipNotificationQueue(NotificationQueue, Protocol):
    def enqueue(self, event_key: str, membership_id: int, event: str, payload: dict) -> dict: ...


class ScheduleNotificationQueue(NotificationQueue, Protocol):
    def delivery_context(self, job: dict) -> dict | None: ...
