  const state = createGymState();
  const { repositories } = getApplicationServices();
  const modules = createGymModules(state, repositories);
  watch(() => [state.authStore.token, state.authStore.userRole, state.authStore.sessionRevision],
    () => state.resetState(), { flush: 'sync' });
  modules.attendance.pruneExpiredAttendancePasses();
