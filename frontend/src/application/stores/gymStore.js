    enrollments: state.enrollments,
    trainerOverview: state.trainerOverview,
    gymSettings: state.gymSettings,
    membershipPayments: state.membershipPayments,
    stats: modules.dashboard.stats,
    recentAttendance: modules.attendance.recentAttendance,
    attendanceAnalytics: modules.attendance.attendanceAnalytics,
    activePlans: modules.memberships.activePlans,
